for (const locale of Object.keys(schedule)) {
  const file = path.join(root, locale, 'translation.json');
  const json = JSON.parse(fs.readFileSync(file, 'utf8'));
  const doctors = ((json.crm = json.crm || {}).doctors = json.crm.doctors || {});
  doctors.schedule = schedule[locale];
  doctors.lookup = lookup[locale];
  doctors.remove = remove[locale];
  fs.writeFileSync(file, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
  console.log(`patched ${locale}`);
}
