/** Latin → Cyrillic for Uzbek, applied to the uz texts (placeholders and the brand-free words survive). */
function toCyrl(text) {
  const parts = text.split(/(\{\{[^}]+\}\})/g);
  return parts
    .map((part) => (part.startsWith("{{") ? part : translit(part)))
    .join("");
}

function translit(s) {
  const pairs = [
    ["Yo'", "Йў"], ["yo'", "йў"], ["Yo‘", "Йў"], ["yo‘", "йў"],
    ["O'", "Ў"], ["o'", "ў"], ["G'", "Ғ"], ["g'", "ғ"], ["O‘", "Ў"], ["o‘", "ў"], ["G‘", "Ғ"], ["g‘", "ғ"],
    ["Sh", "Ш"], ["sh", "ш"], ["SH", "Ш"], ["Ch", "Ч"], ["ch", "ч"], ["CH", "Ч"],
    ["Yo", "Ё"], ["yo", "ё"], ["Yu", "Ю"], ["yu", "ю"], ["Ya", "Я"], ["ya", "я"], ["Ye", "Е"], ["ye", "е"],
    ["Ts", "Ц"], ["ts", "ц"],
  ];
  const single = {
    A: "А", a: "а", B: "Б", b: "б", D: "Д", d: "д", E: "Э", e: "е", F: "Ф", f: "ф", G: "Г", g: "г",
    H: "Ҳ", h: "ҳ", I: "И", i: "и", J: "Ж", j: "ж", K: "К", k: "к", L: "Л", l: "л", M: "М", m: "м",
    N: "Н", n: "н", O: "О", o: "о", P: "П", p: "п", Q: "Қ", q: "қ", R: "Р", r: "р", S: "С", s: "с",
    T: "Т", t: "т", U: "У", u: "у", V: "В", v: "в", X: "Х", x: "х", Y: "Й", y: "й", Z: "З", z: "з",
    "'": "ъ", "’": "ъ",
  };
  let out = "";
  for (let i = 0; i < s.length; ) {
    const pair = pairs.find(([lat]) => s.startsWith(lat, i));
    if (pair) {
      out += pair[1];
      i += pair[0].length;
      continue;
    }
    const ch = s[i];
    // Word-initial "e" is "э", elsewhere "е".
    if ((ch === "e" || ch === "E") && (i === 0 || /[\s«(\-–/:·]/.test(s[i - 1]))) {
      out += ch === "e" ? "э" : "Э";
    } else if (ch === "E") {
      out += "Е";
    } else {
      out += single[ch] ?? ch;
    }
    i += 1;
  }
  return out;
}

const KEEP_LATIN = new Set(["JPG", "PNG", "PDF", "WEBP", "MB", "Push", "CSV"]);

function mapStrings(obj, fn) {
  if (typeof obj === "string") return fn(obj);
  return Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, mapStrings(v, fn)]));
}

const uzCyrl = mapStrings(uz, (text) => {
  let out = toCyrl(text);
  for (const word of KEEP_LATIN) out = out.split(toCyrl(word)).join(word);
  return out;
});
